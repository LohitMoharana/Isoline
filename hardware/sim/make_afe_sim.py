"""Generate and run an ngspice simulation of the Isoline analog front end, driven by a real MIT-BIH segment,
and compare it with the Python AFE model used for all accuracy results.

Circuit (values are the design proposal; op-amp models are behavioural, parameters from datasheets):
  INA333 in-amp, G1 = 1 + 100k/RG = 10 (RG = 11.1k), REF driven by a DC-servo integrator (TLV8541,
  R = 10 MEG, C = 330 nF -> high-pass corner 1/(2*pi*R*C) = 0.048 Hz)
  -> non-inverting gain stage x30 (TLV8541) -> unity-gain Sallen-Key Butterworth LPF 40 Hz (TLV8541)
  Total gain 300: a 0.1 mV input step becomes 30 mV at the comparators, above the TLV3691's 17 mV hysteresis.
  Mid-rail reference 1.5 V, single 3.0 V supply. Electrodes carry a 100 mV DC offset (half-cell mismatch).

Usage: python hardware/sim/make_afe_sim.py <mitdb dir> [record] [t0 s] [dur s]
"""
from __future__ import annotations

import subprocess
import sys
from dataclasses import replace
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from isoline import data  # noqa: E402
from isoline.afe import run_afe  # noqa: E402
from isoline.config import AFEConfig  # noqa: E402
sys.path.insert(0, str(ROOT / "hardware"))
import design as DZ  # noqa: E402  single source of truth shared with the KiCad netlist

HERE = Path(__file__).resolve().parent
GAIN = DZ.TOTAL_GAIN
VREF = DZ.VREF

OPAMP = """
* behavioural single-supply op amp: Aol 120 dB, single pole set by GBW, output clamped to the rails
.subckt OPA inp inn out vcc vee params: gbw=8k
Bdiff n1 0 V = 1e6*(V(inp)-V(inn))
R1 n1 n2 1k
C1 n2 0 {1e6/(2*3.14159265*gbw*1k)}
Bout out 0 V = max(min(V(n2), V(vcc)-0.012), V(vee)+0.012)
.ends
"""


def netlist(t, vin_mv, offset_mv=100.0):
    pwl = " ".join(f"{a:.6f} {b * 1e-3:.7e}" for a, b in zip(t, vin_mv))
    dur = t[-1]
    return f"""* Isoline AFE - generated by make_afe_sim.py
{OPAMP}
VCC vcc 0 {DZ.VSUPPLY}
VREF ref 0 {VREF}
* electrodes: differential ECG + DC offset, common mode at mid-rail
VECG ecg 0 PWL({pwl})
BINP inp 0 V = {VREF} + 0.5*V(ecg) + {offset_mv * 0.5e-3}
BINN inn 0 V = {VREF} - 0.5*V(ecg) - {offset_mv * 0.5e-3}
* INA333: G = 1 + 100k/RG, output = REFpin + G*(in+ - in-), bandwidth ~ 150 kHz/G (datasheet GBW)
BINA ina_o 0 V = max(min(V(srv) + {DZ.INA_G1:.4f}*(V(inp)-V(inn)), 2.95), 0.05)
* DC servo: integrator drives the in-amp REF pin -> first-order high-pass at 1/(2*pi*Rs*Cs)
Rs ina_o s_in {DZ.SERVO_R}
Cs s_in srv {DZ.SERVO_C}
XS ref s_in srv vcc 0 OPA gbw=8k
* gain stage x30 (non-inverting about VREF)
Rg1 g_inv ref {DZ.G2_RG}
Rf1 g_inv g_out {DZ.G2_RF}
XG ina_o g_inv g_out vcc 0 OPA gbw=8k
* unity-gain Sallen-Key Butterworth LPF, fc = 40 Hz (R = 100k, C1 = 56n, C2 = 27n)
R1 g_out sk1 {DZ.SK_R1}
R2 sk1 sk2 {DZ.SK_R2}
C1 sk1 out {DZ.SK_C1}
C2 sk2 ref {DZ.SK_C2}
XL sk2 out out vcc 0 OPA gbw=8k
.options method=gear reltol=1e-4
* servo pre-charged to its steady state (what a fast-restore switch achieves at power-up)
.ic v(srv)={VREF - DZ.INA_G1 * offset_mv * 1e-3:.4f} v(s_in)={VREF}
.control
tran 0.5m {dur:.3f} 0 0.5m uic
wrdata afe_out.txt v(out) v(ina_o) v(srv)
quit
.endc
.end
"""


def level_cross(y, step):
    """Counts every step crossed (several per 360 Hz sample on steep QRS edges), like isoline.afe."""
    up = np.zeros(len(y), int); dn = np.zeros(len(y), int); ref = y[0]
    for i, v in enumerate(y):
        while v >= ref + step:
            up[i] += 1; ref += step
        while v <= ref - step:
            dn[i] += 1; ref -= step
    return up, dn


def main():
    D = sys.argv[1]; rec = sys.argv[2] if len(sys.argv) > 2 else "101"
    t0 = float(sys.argv[3]) if len(sys.argv) > 3 else 20.0; dur = float(sys.argv[4]) if len(sys.argv) > 4 else 12.0
    x, _, _ = data.load_mitdb_record(D, rec)
    s, e = int(t0 * 360), int((t0 + dur) * 360)
    seg = x[s:e] - np.median(x[s:e])
    t = np.arange(len(seg)) / 360
    (HERE / "afe.cir").write_text(netlist(t, seg))
    r = subprocess.run(["ngspice", "-b", "afe.cir"], capture_output=True, text=True, cwd=HERE)
    if r.returncode != 0:
        print(r.stdout[-2000:], r.stderr[-2000:]); raise SystemExit(1)
    out = np.loadtxt(HERE / "afe_out.txt")
    ts, vout = out[:, 0], out[:, 1]
    vo = np.interp(t, ts, vout)                         # resample to 360 Hz (the comparator readout clock)
    y_spice_mv = (vo - VREF) / GAIN * 1e3               # input-referred mV
    # Python AFE model at the same settings (HPF 0.05 Hz first order, LPF 40 Hz 2nd order)
    cfg = replace(AFEConfig(), delta_mv=0.1, hp_hz=0.05)
    up_p, dn_p, y_py = run_afe(seg, cfg, np.random.default_rng(0))
    settle = int(2 * 360)                               # ignore the first 2 s (filter start-up)
    a, b = y_spice_mv[settle:], y_py[settle:]
    corr = np.corrcoef(a - a.mean(), b - b.mean())[0, 1]
    rms = np.sqrt(np.mean(((a - a.mean()) - (b - b.mean())) ** 2))
    up_s, dn_s = level_cross(vo[settle:], 0.1e-3 * GAIN)
    n_s, n_p = int(up_s.sum() + dn_s.sum()), int(up_p[settle:].sum() + dn_p[settle:].sum())
    swing = (vout.min(), vout.max())
    lines = [f"record {rec}, {t0:.0f}-{t0 + dur:.0f} s, electrode DC offset 100 mV",
             f"ngspice output swing {swing[0]:.3f} .. {swing[1]:.3f} V (rails 0..3 V)",
             f"waveform match after 2 s settling: correlation {corr:.4f}, RMS difference {1e3 * rms:.1f} uV input-referred",
             f"level-crossing events (dV = 0.1 mV input = {0.1 * GAIN:.0f} mV at comparators): ngspice {n_s}, Python model {n_p} "
             f"({100 * (n_s - n_p) / max(n_p, 1):+.1f} %)"]
    print("\n".join(lines))
    (ROOT / "results" / "hardware" / "afe_vs_python.txt").write_text("\n".join(lines) + "\n")
    np.savez(HERE / "afe_traces.npz", t=t, spice_mv=y_spice_mv, python_mv=y_py)


if __name__ == "__main__":
    main()
